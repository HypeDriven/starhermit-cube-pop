// Writes the play scripts in tests/native/ that drive the real UI through
// whole rounds, from the rules: js/rules.js and js/session.js run here in node
// (vm), a greedy player picks each pop (the largest group of a colour a goal
// still needs, else the largest group), and the script moves the focus there
// with the arrow keys, pops with Enter and waits out the wall's animation
// (its length worked out as native/render.ts playEvents does) before the next
// key. Boards are seeded by their content, so the scripts replay exactly.
//   node tools/gen-plays.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const ROOT = new URL('..', import.meta.url).pathname;
const ctx = vm.createContext({ localStorage: { getItem: () => null, setItem() {}, removeItem() {} }, performance: { now: () => 0 } });
for (const f of ['rng', 'rules', 'content', 'session']) vm.runInContext(readFileSync(`${ROOT}js/${f}.js`, 'utf8'), ctx);
const { CPRules: R, CPContent: C, CPSession: S } = ctx;

/** native/render.ts playEvents: the move's animation in ms. */
function animMs(events) {
  let t = 0, blastN = 0;
  for (const ev of events) {
    if (ev.type === 'pop') t += 160 + Math.min((ev.cells || []).length * 12, 90);
    else if (ev.type === 'special-create') t += 80;
    else if (ev.type === 'fire') t += 60;
    else if (ev.type === 'blast') { blastN++; t += 260 * 0.7; }
    else if (ev.type === 'fall') t += 220;
    else if (ev.type === 'refill') t += 340;
    else if (ev.type === 'shuffle') t += 450;
    else if (ev.type === 'wave' || ev.type === 'win') t += 200;
  }
  return t + 30 + blastN * 90;
}

class Script {
  constructor(head) { this.lines = head.map((l) => `# ${l}`); this.focus = { r: 0, c: 0 }; }
  add(...l) { this.lines.push(...l); return this; }
  moveTo(r, c) {
    while (this.focus.r < r) { this.add('key ArrowDown 1', 'frames 1'); this.focus.r++; }
    while (this.focus.r > r) { this.add('key ArrowUp 1', 'frames 1'); this.focus.r--; }
    while (this.focus.c < c) { this.add('key ArrowRight 1', 'frames 1'); this.focus.c++; }
    while (this.focus.c > c) { this.add('key ArrowLeft 1', 'frames 1'); this.focus.c--; }
  }
  /** Moves there, pops, waits out the animation. */
  pop(session, r, c, id) {
    this.moveTo(r, c);
    const res = session.pop(r, c, id);
    if (!res.ok) throw new Error(`illegal pop ${r},${c}: ${res.reason}`);
    this.add('key Enter 1', `frames ${Math.ceil(animMs(res.events) / (1000 / 60)) + 12}`);
    return res;
  }
  /** The round's countdown (3, 2, 1, Pop!: 2.05 s) and a little more. */
  countdown() { this.focus = { r: 0, c: 0 }; return this.add('frames 150'); }
  write(name) { writeFileSync(`${ROOT}tests/native/${name}`, this.lines.join('\n') + '\n'); console.log(`wrote tests/native/${name} (${this.lines.length} lines)`); }
}

/** The greedy player's next pop: the largest group of a colour a goal still needs, else the largest. */
function choose(state) {
  const acts = R.legalActions(state);
  let best = null, score = -1;
  for (const a of acts) {
    const cell = state.grid[a.r][a.c];
    const need = a.kind === 'pop' && state.cfg.goals[cell.c] != null && (state.goals[cell.c] || 0) < state.cfg.goals[cell.c];
    const v = (need ? 1000 : 0) + a.size + (a.kind === 'fire' ? 500 : 0);
    if (v > score) { score = v; best = a; }
  }
  return best;
}
function playToEnd(sc, session, limit = 80) {
  let n = 0;
  while (!session.state.terminal && n < limit) { const a = choose(session.state); sc.pop(session, a.r, a.c, `g${++n}`); }
  if (!session.state.terminal) throw new Error('did not finish');
  return n;
}

// -- journey stage 1 to the results, then Next opens stage 2 -------------------------------
{
  const cfg = C.JOURNEY[0];
  const sc = new Script([
    'Generated by tools/gen-plays.mjs: journey stage 1 (First Pops) from the Journey list, played by keys to',
    'the results (a greedy player: the largest group a goal still needs), then Next opens stage 2.',
  ]);
  sc.add('until 300 Cube Pop', 'frames 30', 'click =Journey', 'until 60 Forty authored stages', 'frames 10', 'save journey', 'click First Pops', 'until 120 Goals');
  sc.countdown();
  sc.add('save stage-1');
  const s = new S.Session(cfg);
  const n = playToEnd(sc, s);
  if (!s.state.terminal.won) throw new Error('stage 1 lost');
  sc.add('until 300 You win', 'frames 20', 'expect Total', 'save results', 'click =Next', 'until 200 Cherry 0 / 12');
  sc.countdown();
  sc.add('save stage-2', 'key Escape 1', 'until 60 Leave round', 'frames 10', 'click =Leave round', 'until 120 Resume saved round', 'frames 10');
  sc.write('journey-first-stage.play');
  console.log(`  stage 1: ${n} pops, ${s.state.score.total} points`);
}

// -- the seven lessons through Learn and Next ------------------------------------------------
{
  const lessons = C.tutorialLessons();
  const sc = new Script(['Generated by tools/gen-plays.mjs: the seven Learn lessons, each by the move its goal asks for, through Next.']);
  sc.add('until 300 Cube Pop', 'frames 30', 'click =Learn', 'until 60 Interactive lessons', 'frames 10', 'save learn', 'click 1. Pop a group', 'until 120 Goals');
  lessons.forEach((lesson, i) => {
    sc.countdown();
    const s = new S.Session(lesson.cfg, { lesson, forcedGrid: lesson.force.grid, forcedSpecials: lesson.force.specials || [] });
    if (lesson.goal.event === 'undo') {
      const a = R.legalActions(s.state).find((x) => x.kind === 'pop');
      sc.pop(s, a.r, a.c, 'u1');
      s.undo();
      sc.add('key KeyU 1', 'frames 5');
    } else {
      // The move whose events meet the goal (a win for "Finish the stage").
      const acts = R.legalActions(s.state).filter((x, j, all) => all.findIndex((y) => y.r === x.r && y.c === x.c) === j);
      const pick = acts.find((a) => {
        const t = new S.Session(lesson.cfg, { lesson, forcedGrid: lesson.force.grid, forcedSpecials: lesson.force.specials || [] });
        t.pop(a.r, a.c, 'x');
        return t.lessonGoalMet();
      });
      if (!pick) throw new Error(`no move meets lesson ${lesson.id}`);
      sc.pop(s, pick.r, pick.c, 'l1');
    }
    if (!s.lessonGoalMet()) throw new Error(`lesson ${lesson.id} not met`);
    sc.add(`until 120 Lesson complete: ${lesson.title}`, 'frames 10');
    if (i === 0) sc.add('save lesson-done');
    if (i < lessons.length - 1) sc.add('click =Next', `until 120 ${lessons[i + 1].title}`);
  });
  sc.add('click =Menu', 'until 120 Play: First Pops', 'click =Learn', 'until 60 Interactive lessons', 'frames 10', 'save learn-done', 'key Escape 1', 'until 60 Play: First Pops');
  sc.write('learn-lessons.play');
}

// -- practice: undo, hint, pause and resume the saved round ------------------------------------
{
  const cfg = C.PRACTICE[0];
  const sc = new Script([
    'Generated by tools/gen-plays.mjs: Practice › Casual: a pop, Undo, a Hint, a refused pop, then Pause,',
    'Leave round and Resume saved round from the title, then the round to its results.',
  ]);
  sc.add('until 300 Cube Pop', 'frames 30', 'click =Practice', 'until 60 Unranked', 'frames 10', 'click Casual', 'until 120 Goals');
  sc.countdown();
  const s = new S.Session(cfg);
  const a = choose(s.state);
  sc.pop(s, a.r, a.c, 'p1');
  sc.add('key KeyU 1', 'until 30 Move undone', 'frames 5');
  s.undo();
  sc.add('key KeyH 1', 'until 30 Hint:', 'frames 10', 'save hint');
  const h = s.hint();
  sc.moveTo(h.r, h.c);
  // A refused pop: a lone cube (group of 1) if one exists.
  let lone = null;
  for (let r = 0; r < s.state.grid.length && !lone; r++) for (let c = 0; c < s.state.grid[0].length && !lone; c++) {
    const cell = s.state.grid[r][c];
    if (cell && cell.s === 0 && R.groupAt(s.state, r, c).length < 2) lone = { r, c };
  }
  if (lone) { sc.moveTo(lone.r, lone.c); sc.add('key Enter 1', 'until 30 is not in a group', 'frames 5'); }
  sc.add('key Escape 1', 'until 60 Restart round', 'frames 10', 'save pause', 'click =Leave round', 'until 120 Resume saved round', 'frames 10', 'click =Resume saved round', 'until 120 Goals');
  sc.countdown();
  playToEnd(sc, s);
  sc.add('until 300 You win', 'frames 10', 'expect Total', 'click =Menu', 'until 120 Play: First Pops');
  sc.write('practice-assists.play');
}

// -- a timed challenge running out ---------------------------------------------------------------
{
  const cfg = C.CHALLENGES.find((c) => c.id === 'c2');
  const sc = new Script(['Generated by tools/gen-plays.mjs: Challenge › Speed Pop (90 s): three pops, then the clock runs out (the', '15-second warning, then Time is up on the results).']);
  sc.add('until 300 Cube Pop', 'frames 30', 'click =Challenge', 'until 60 Constrained goals', 'frames 10', 'click Speed Pop', 'until 120 Goals');
  sc.countdown();
  const s = new S.Session(cfg);
  for (let i = 0; i < 3; i++) { const a = choose(s.state); sc.pop(s, a.r, a.c, `t${i}`); }
  sc.add('until 6000 15 seconds left', 'save time-warning', 'until 1200 Time is up', 'frames 10', 'save time-up', 'click =Menu', 'until 120 Play: First Pops');
  sc.write('challenge-timer.play');
}
